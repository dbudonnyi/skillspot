export const dictionaries: Record<Locale, Dict> = { en, pl, uk };

export function detectLocaleFromAcceptLanguage(header: string | null): Locale {
  if (!header) return "en";
  const prefs = header
    .split(",")
    .map((p) => {
      const [tag, q] = p.trim().split(";q=");
      return { tag: tag.trim().toLowerCase(), q: q ? parseFloat(q) : 1 };
    })
    .sort((a, b) => b.q - a.q);
  for (const { tag } of prefs) {
    if (tag.startsWith("pl")) return "pl";
    if (tag.startsWith("uk") || tag.startsWith("ru")) return "uk";
    if (tag.startsWith("en")) return "en";
  }
  return "en";
}

export function isLocale(v: unknown): v is Locale {
  return typeof v === "string" && (LOCALES as readonly string[]).includes(v);
}

/** interpolate {placeholders} */
export function fmt(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  return template.replace(/\{\{?(\w+)\}?\}/g, (m, k) =>
    params[k] !== undefined ? String(params[k]) : m,
  );
}

export function tr(dict: Dict, key: string, params?: Record<string, string | number>): string {
  const raw = dict[key] ?? en[key] ?? key;
  return fmt(raw, params);
}
